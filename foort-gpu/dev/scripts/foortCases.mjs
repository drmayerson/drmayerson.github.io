// M2 parity cases: one definition drives both the FOORT config and the CPU reference tracer.
// Cameras and emission parameters from FOORT's example configs; integrator forced to RK4
// (the examples use Verlet); SimpleSquareMesh; boundary sphere 1.01 r_cam (plan Section 3.7).
import { createKerr } from '../../js/metrics/kerr.js';
import { createJohannsen } from '../../js/metrics/johannsen.js';
import { createMankoNovikov } from '../../js/metrics/mankoNovikov.js';
import { createST3Cr } from '../../js/metrics/st3cr.js';

const kerrCam = { r: 1000, theta: 0.2967, screen: 15 };
const kerrEmission = { mu: 2.02, gamma: -2.0, sigma: 0.5 };

/**
 * @typedef {Object} ParityCase
 * @property {string} name
 * @property {string} metricCfg      FOORT Metric block body
 * @property {() => any} create      JS metric
 * @property {{r:number, theta:number, screen:number}} camera
 * @property {number} N              pixels per side
 * @property {number} maxSteps
 * @property {number} epsHorizon     FOORT Epsilon_Horizon (relative to r_h; absolute r cut if r_h = 0)
 * @property {number} horizonRadius  r_h used by FOORT's Horizon termination (0 for ST3Cr)
 * @property {boolean} thetaSing     FOORT ThetaSingularity termination on/off (eps 1e-6)
 * @property {number|null} singEps   FOORT GeneralSingularity epsilon (coordinate distance), null = off
 * @property {{mu:number, gamma:number, sigma:number}} emission  Johnson-SU (for M5; FOORT output kept now)
 */

const mn = createMankoNovikov({ a: 0.94, alpha3: 2 });
const mnEps = mn.terminationRadius() / mn.horizon.r - 1;

/** @type {ParityCase[]} */
export const CASES = [
  { name: 'kerr_a0', metricCfg: 'Name = "Kerr"; a = 0.0;', create: () => createKerr({ a: 0 }), camera: kerrCam, N: 128, maxSteps: 100000,
    epsHorizon: 0.01, horizonRadius: 2, thetaSing: true, singEps: null, emission: kerrEmission },
  { name: 'kerr_a0.94', metricCfg: 'Name = "Kerr"; a = 0.94;', create: () => createKerr({ a: 0.94 }), camera: kerrCam, N: 128, maxSteps: 100000,
    epsHorizon: 0.01, horizonRadius: createKerr({ a: 0.94 }).horizon.r, thetaSing: true, singEps: null, emission: kerrEmission },
  { name: 'johannsen', metricCfg: 'Name = "Johannsen"; a = 0.94; alpha13 = 5.5;', create: () => createJohannsen({ a: 0.94, alpha13: 5.5 }), camera: kerrCam, N: 128, maxSteps: 100000,
    epsHorizon: 0.01, horizonRadius: createKerr({ a: 0.94 }).horizon.r, thetaSing: true, singEps: null, emission: kerrEmission },
  { name: 'mankoNovikov', metricCfg: 'Name = "Manko-Novikov"; a = 0.94; alpha3 = 2.0;', create: () => createMankoNovikov({ a: 0.94, alpha3: 2 }),
    camera: { r: 1000, theta: 0.523599, screen: 15 }, N: 128, maxSteps: 10000,
    epsHorizon: mnEps, horizonRadius: mn.horizon.r, thetaSing: true, singEps: null, emission: kerrEmission },
  { name: 'st3cr_l0.005', metricCfg: 'Name = "ST3Cr"; P = 2.0; q0 = 50.0; lambda = 0.005;', create: () => createST3Cr({ P: 2, q0: 50, lambda: 0.005 }),
    camera: { r: 250, theta: 1.5, screen: 150 }, N: 128, maxSteps: 10000,
    epsHorizon: 0.01, horizonRadius: 0, thetaSing: false, singEps: 0.001, emission: { mu: 0, gamma: -1.5, sigma: 2 } },
];

/** libconfig reals must contain a '.' or exponent; an integer literal is silently ignored by FOORT's real lookups. @param {number} x */
const fl = (x) => { const s = String(x); return /[.eE]/.test(s) ? s : s + '.0'; };

/**
 * FOORT config text for a case. @param {ParityCase} c @param {string} outPrefix forward-slash path
 * @param {{derivativeH?: number}} [opts]  FOORT Integrator DerivativeH (finite-difference step of its Christoffels; default 1e-7)
 */
export function foortConfig(c, outPrefix, opts = {}) {
  const e = c.emission;
  return `// generated by foort-gpu/dev/scripts/foortCases.mjs (${c.name})
Metric = { ${c.metricCfg} RLogScale = true; };
Diagnostics = {
  FourColorScreen = { On = true; UseForMesh = false; };
  GeodesicPosition = { On = true; OutputSteps = 1; UpdateFrequency = 1; UpdateStart = false; UpdateFinish = true; UseForMesh = false; };
  EquatorialEmission = { On = true; UseForMesh = true; Threshold = 0.001; GeometricFudgeFactor = 1.0; EquatPassUpperBound = 0;
    EmissionModel = "GLMJohnsonSU"; mu = ${fl(e.mu)}; gamma = ${fl(e.gamma)}; sigma = ${fl(e.sigma)};
    FluidVelocityModel = "GeneralCircularRadial"; xi = 1.0; betar = 1.0; betaphi = 1.0; };
};
Terminations = {
  Horizon = { On = true; Epsilon_Horizon = ${fl(c.epsHorizon)}; };
  BoundarySphere = { On = true; SphereRadius = ${fl(1.01 * c.camera.r)}; };
  TimeOut = { On = true; MaxSteps = ${c.maxSteps}; };
  ThetaSingularity = { On = ${c.thetaSing}; Epsilon = 1e-6; };
  NaN = { On = true; ConsoleOutput = false; };
  GeneralSingularity = { On = ${c.singEps !== null}; ConsoleOutput = false; Epsilon = ${fl(c.singEps ?? 0.001)}; };
};
ViewScreen = {
  Position = { t = 0.0; r = ${fl(c.camera.r)}; theta = ${fl(c.camera.theta)}; phi = 0.0; };
  Direction = { t = 0.0; r = -1.0; theta = 0.0; phi = 0.0; };
  ScreenSize = { x = ${fl(c.camera.screen)}; y = ${fl(c.camera.screen)}; };
  ScreenCenter = { x = 0.0; y = 0.0; };
  Mesh = { Type = "SimpleSquareMesh"; TotalPixels = ${c.N * c.N}; };
};
Source = { Name = "NoSource"; };
Integrator = { Type = "RK4"; StepSize = 0.03; SmallestPossibleStepsize = 1e-12;${opts.derivativeH ? ` DerivativeH = ${opts.derivativeH.toExponential()};` : ''} };
Output = {
  FilePrefix = "${outPrefix}"; FileExtension = "dat"; TimeStamp = false;
  GeodesicsToCache = 1000000; GeodesicsPerFile = 1000000; FirstLineInfo = true;
  ScreenOutputLevel = 1; LoopMessageFrequency = 100000;
};
`;
}
